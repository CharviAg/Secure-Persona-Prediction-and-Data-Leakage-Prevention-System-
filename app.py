def register_page():
    show_brand()
    st.write("")

    st.markdown("## Create your account")
    st.write("Register to start using Customer Persona Analytics.")

    with st.form("register_form"):
        name = st.text_input("Full name")
        email = st.text_input("Email address")
        phone = st.text_input("Phone number")
        username = st.text_input("Choose a username")
        password = st.text_input("Create password", type="password")
        confirm_password = st.text_input(
            "Confirm password",
            type="password",
        )

        if password:
            strength = check_password_strength(password)

            if strength == "Strong":
                st.success("Password strength: Strong")
            elif strength == "Medium":
                st.warning("Password strength: Medium")
            else:
                st.error("Password strength: Weak")

        submitted = st.form_submit_button(
            "Create account",
            use_container_width=True,
        )

    if submitted:
        if not all(
            [
                name.strip(),
                email.strip(),
                phone.strip(),
                username.strip(),
                password,
                confirm_password,
            ]
        ):
            st.error("Please complete every field.")
        elif "@" not in email or "." not in email.split("@")[-1]:
            st.error("Please enter a valid email address.")
        elif len(password) < 8:
            st.error("Your password must contain at least 8 characters.")
        elif password != confirm_password:
            st.error("The passwords do not match.")
        else:
            try:
                register_user(
                    name.strip(),
                    email.strip().lower(),
                    phone.strip(),
                    username.strip(),
                    hash_password(password),
                )
                st.success("Account created successfully! You can now log in.")
                st.session_state.page = "Login"
                st.rerun()

            except sqlite3.IntegrityError:
                st.error(
                    "That username or email is already registered. "
                    "Please choose another."
                )
            except Exception as error:
                st.error(f"Could not create account: {error}")

    if st.button("Already have an account? Login"):
        st.session_state.page = "Login"
        st.rerun()

    if st.button("Back to welcome page"):
        st.session_state.page = "Welcome"
        st.rerun()


